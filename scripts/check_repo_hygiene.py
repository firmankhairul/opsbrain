#!/usr/bin/env python3
"""Repo hygiene gate.

Enforces the structural rules in CLAUDE.md that used to drift silently:
slug naming, no duplicate customer folders, no per-user agent droppings,
no generated skill mirrors, no PII/credential exports, no giant blobs.

Run locally:  python3 scripts/check_repo_hygiene.py
Exit code 1 on any violation, so it can gate a PR.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from audit_customer_completeness import IGNORED  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[1]

SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
MAX_TRACKED_BYTES = 5 * 1024 * 1024

# Blank templates the whole team needs (generate_ppt.py reads it). Exempt by exact path,
# not by extension: a filled customer deck is still a deliverable and still capped.
SIZE_EXEMPT = {"monthly-report/template/Template.pptx"}

# Filenames that must never be committed, whatever directory they land in.
SECRET_PATTERNS = [
    re.compile(r"cognito_login-.*\.csv$", re.I),
    re.compile(r"_users[-_]\d{8}.*\.csv$", re.I),
    re.compile(r"accessKeys.*\.csv$", re.I),
    re.compile(r"credentials.*\.csv$", re.I),
    re.compile(r"\.pem$|\.ppk$|(^|/)id_rsa$", re.I),
]

# Per-user agent scratch that belongs on a laptop, not in the team repo.
DROPPING_RE = re.compile(
    r"(^|/)(memory|sessions|prompts|\.codewhale)/"
    r"|(?<!^)(^|/)\.claude/"
)

# Generated by scripts/sync-skills.sh from .claude/skills/ — never committed.
# NOTE: .kiro/steering/ is NOT entirely generated — only ops-rules.md there is
# a mirror. ops.md and graphify.md are hand-authored Kiro-specific content
# (see CLAUDE.md customer workspace contract history) and must stay tracked.
MIRROR_PREFIXES = (
    ".kiro/skills/", ".kiro/steering/ops-rules.md", ".gemini/skills/",
    ".agents/skills/", ".opencode/agents/",
)


def tracked_files() -> list[str]:
    out = subprocess.run(
        ["git", "-C", str(REPO_ROOT), "ls-files"],
        capture_output=True, text=True, check=True,
    )
    return out.stdout.splitlines()


def check_slugs(problems: list[str]) -> None:
    for path in sorted(REPO_ROOT.iterdir()):
        if not path.is_dir() or path.name in IGNORED or path.name.startswith(".") or path.name.endswith(".egg-info"):
            continue
        if not SLUG_RE.match(path.name):
            problems.append(
                f"slug: '{path.name}/' is not lowercase kebab-case "
                f"(no capitals, spaces or dots)"
            )
        yaml_file = path / "customer.yaml"
        if yaml_file.exists():
            for line in yaml_file.read_text().splitlines():
                if line.startswith("folder:"):
                    declared = line.split(":", 1)[1].strip()
                    if declared != path.name:
                        problems.append(
                            f"slug: {path.name}/customer.yaml declares "
                            f"folder: {declared!r}, must match the folder name"
                        )
                    break


def check_case_duplicates(problems: list[str]) -> None:
    seen: dict[str, str] = {}
    for path in sorted(REPO_ROOT.iterdir()):
        if not path.is_dir() or path.name.startswith(".") or path.name in IGNORED or path.name.endswith(".egg-info"):
            continue
        key = path.name.lower()
        if key in seen:
            problems.append(
                f"duplicate: '{seen[key]}/' and '{path.name}/' differ only by case "
                f"— one customer, one folder"
            )
        seen[key] = path.name


def check_files(files: list[str], problems: list[str]) -> None:
    for f in files:
        name = f.rsplit("/", 1)[-1]
        for pat in SECRET_PATTERNS:
            if pat.search(name):
                problems.append(f"secret/PII: {f} must never be committed")
                break
        if DROPPING_RE.search("/" + f):
            problems.append(f"dropping: {f} is per-user agent scratch, not repo content")
        if f.startswith(MIRROR_PREFIXES):
            problems.append(
                f"mirror: {f} is generated by scripts/sync-skills.sh — commit "
                f".claude/skills/ only"
            )
        blob = REPO_ROOT / f
        if f not in SIZE_EXEMPT and blob.is_file() and blob.stat().st_size > MAX_TRACKED_BYTES:
            mb = blob.stat().st_size / 1024 / 1024
            problems.append(f"size: {f} is {mb:.1f} MB (limit 5 MB)")


# Tickets created from this date on must carry a filled `Bobot kerja` and real content
# in the blocks that answer the five PM questions. Dated rather than applied to
# everything because 188 legacy tickets predate the standard, and backfilling them
# would mean guessing 188 weights — false precision in KPI data for work that is mostly
# closed. See docs/standards/ops-issue-format.md §6.3 of the rollout plan.
TICKET_RULES_FROM = "2026-10-01"

_TICKET_DATE = re.compile(r"(?:^|/)(?:TKT-)?(\d{4}-\d{2}-\d{2})-")
_WEIGHT_NUM = re.compile(r"\*\*Bobot kerja:?\*\*\s*(\d+)", re.IGNORECASE)
_PLACEHOLDER_ROW = re.compile(r"^\|\s*\d+\s*\|\s*\|", re.MULTILINE)
_BANNER = re.compile(r"^>\s*\*\*Status:\*\*", re.MULTILINE)


def check_new_tickets(files: list[str], notes: list[str]) -> None:
    """Report what the scaffold cannot fill in for you. INFORMATIONAL, not a gate.

    The shape comes out right automatically; the substance does not. An unfilled
    `Bobot kerja` parses as nothing and disappears from capacity totals with no warning,
    and an empty action-items row means the issue body cannot answer "whose ball".

    Added as a hard gate on 2026-10-01 and demoted on 2026-10-05, after it failed CI
    seven times running on `acme-retail/tickets/TKT-2026-10-03-acme-retail-hardware-failure.md`
    — a hand-written incident ticket with a correct banner that simply had no weight
    line. That contradicted this repo's own stated rule, written directly above where
    the gate was added: content debt is informational, structural rot is the hard gate.
    Blocking on it took the checks that DO matter (secrets, slugs, blob size) down with
    it, and seven red emails in a row teach people to ignore red.

    The report still runs, so the debt stays visible in the log.
    """
    for f in files:
        if "/tickets/" not in f or not f.endswith(".md"):
            continue
        m = _TICKET_DATE.search(f)
        if not m or m.group(1) < TICKET_RULES_FROM:
            continue
        path = REPO_ROOT / f
        if not path.is_file():
            continue
        text = path.read_text(errors="replace")
        if not _BANNER.search(text):
            notes.append(f"ticket: {f} has no status banner "
                            f"(docs/standards/ops-issue-format.md, 5 blocks)")
            continue
        if not _WEIGHT_NUM.search(text):
            # "no numeric weight" covers both an unfilled `<n>` and no line at all; the
            # earlier wording said "unfilled" for a ticket that simply had none.
            notes.append(f"ticket: {f} has no numeric `Bobot kerja` — it is dropped "
                         f"from capacity totals silently. Fill it in from the weight table "
                         f"in docs/standards/ops-issue-format.md (env, and priority for an incident)")
        if _PLACEHOLDER_ROW.search(text):
            notes.append(f"ticket: {f} still has the empty action-items placeholder "
                            f"row — the body cannot answer 'whose ball' without it")
        if "## Referensi" in text:
            notes.append(f"ticket: {f} has `## Referensi`, dropped 2026-09-30 — "
                            f"documents go in the `Dokumen` row of `## Environment`")


def main() -> int:
    problems: list[str] = []
    notes: list[str] = []
    check_slugs(problems)
    check_case_duplicates(problems)
    files = tracked_files()
    check_files(files, problems)
    check_new_tickets(files, notes)

    if notes:
        print(f"Ticket format: {len(notes)} note(s) — informational, does not fail "
              f"the build\n")
        for n in sorted(set(notes)):
            print(f"  {n}")
        print("\nSee docs/standards/ops-issue-format.md\n")

    if problems:
        print(f"Repo hygiene: {len(problems)} violation(s)\n")
        for p in sorted(set(problems)):
            print(f"  {p}")
        print("\nSee CLAUDE.md 'Customer workspace contract' for the rules.")
        return 1

    print("Repo hygiene: clean.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
